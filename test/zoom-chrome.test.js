import test from "node:test";
import assert from "node:assert/strict";
import { chrome, runInChrome } from "../test-support/chrome.js";

test("real Chrome DOM: Zoom captions are read from the visible subtitle box only", { skip: !chrome, timeout: 40000 }, async t => {
  const suite = async function (window, capture) {
    let checks = 0, owner = "zoom-1";
    const eq = (a, b, name) => { if (JSON.stringify(a) !== JSON.stringify(b)) throw Error(name + ": " + JSON.stringify(a)); checks++; };
    const tick = () => new Promise(r => setTimeout(r, 30));
    const call = (action, extra = {}) => capture({ action, meetingId: "app.zoom.us/wc/12345678", captureId: owner, ...extra });
    const frame = document.createElement("iframe"); frame.id = "webclient"; document.body.append(frame);
    const doc = frame.contentDocument; doc.body.innerHTML = "<p id='tile'>Alice</p>";
    const mount = () => { const box = doc.createElement("div"); box.className = "live-transcription-subtitle__box"; doc.body.append(box); return box; };
    const addRow = (box, avatar, text) => { const row = doc.createElement("div"), img = doc.createElement("img"), span = doc.createElement("span"); img.src = "https://example.invalid/" + avatar + ".png"; span.textContent = text; row.append(img, span); box.append(row); return span; };
    const texts = () => call("read").blocks.map(b => b.transcript);
    eq(call("discover").code, "READY", "frame found, caption box not required");
    let box = mount(); const old = addRow(box, "a1", "history before start");
    eq(call("start").status, "live", "starts");
    old.textContent = "history before start and more"; await tick();
    eq(texts(), [], "text that was already showing at start is never sent, including its growth");
    const fresh = addRow(box, "a2", "hello"); await tick();
    fresh.textContent = "hello world"; await tick();
    eq(texts(), ["hello world"], "new row is upserted under one id");
    const read = call("read"); eq(read.blocks[0].messageVersion >= 2, true, "revisions counted");
    fresh.textContent = "world again"; await tick();
    eq(texts(), ["hello world again"], "left-truncated rolling text is accumulated");
    const second = addRow(box, "a3", "other speaker"); await tick();
    eq(call("read").blocks.map(b => b.deviceId), ["speaker-2", "speaker-3"], "speakers are anonymous, numbered by avatar in order of first sight");
    eq(JSON.stringify(call("read")).includes("a2.png") || JSON.stringify(call("read")).includes("Alice"), false, "avatar urls and names never leave the page");
    fresh.textContent = "a completely new sentence"; await tick();
    eq(texts(), ["hello world again", "other speaker", "a completely new sentence"], "unrelated text on a reused row is a new utterance");
    const before = doc.documentElement.outerHTML; call("read"); eq(doc.documentElement.outerHTML, before, "reader never mutates the page");
    box.remove(); await tick(); eq(call("read").status, "live", "caption box disappearing is not an error");
    box = mount(); addRow(box, "a3", "other speaker"); const again = addRow(box, "a2", "after remount"); await tick(); call("read"); again.textContent = "after remount grows"; await tick();
    eq(texts().includes("after remount grows"), true, "a new caption box is re-observed");
    eq(texts().filter(x => x === "other speaker").length, 1, "a re-rendered row of an already seen utterance is not sent again");
    box.append(Object.assign(doc.createElement("div"), { textContent: "unstructured text" }));
    again.textContent = "x"; box.querySelector("img")?.remove(); box.innerHTML = "<div>no avatar rows</div>";
    eq(call("read").code, "CAPTION_FORMAT_UNKNOWN", "unknown structure stops instead of guessing");
    call("reset"); box.innerHTML = ""; const keep = addRow(box, "a9", "existing again");
    owner = "zoom-2"; call("start"); await new Promise(r => setTimeout(r, 2150));
    eq(call("read").code, "CAPTURE_EXPIRED", "lease expires");
    eq(call("recover", { captureId: "zoom-3", previousCaptureId: owner }).status, "live", "recover continues");
    owner = "zoom-3"; keep.textContent = "existing again, grown"; await tick();
    eq(texts(), [], "text showing at recovery is excluded again");
    addRow(box, "a9", "brand new"); await tick();
    eq(texts(), ["brand new"], "new rows after recovery are read");
    call("reset");
    return { ok: true, checks };
  };
  const result = await runInChrome(t, { hook: "zoom-hook.js", hostname: "app.zoom.us", pathname: "/wc/12345678/join", suite });
  assert.ok(result.checks >= 14);
  t.diagnostic(`Chrome DOM (Zoom): ${result.checks} assertions on a synthetic subtitle box; no live meeting.`);
});
