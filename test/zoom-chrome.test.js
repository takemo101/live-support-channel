import test from "node:test";
import assert from "node:assert/strict";
import { chrome, runInChrome } from "../test-support/chrome.js";

test("real Chrome DOM: Zoom captions are intercepted from the app store found through the React tree", { skip: !chrome, timeout: 40000 }, async t => {
  const suite = async function (window, capture) {
    let checks = 0, owner = "zoom-1";
    const eq = (a, b, name) => { if (JSON.stringify(a) !== JSON.stringify(b)) throw Error(name + ": " + JSON.stringify(a)); checks++; };
    const call = (action, extra = {}) => capture({ action, meetingId: "app.zoom.us/wc/12345678", captureId: owner, ...extra });
    const texts = () => call("read").blocks.map(b => [b.deviceId, b.speakerName, b.transcript]);
    const state = { newLiveTranscription: { newLTMessage: { old: { msgId: "old", user: { zoomID: 1, displayName: "Alice Example" }, text: "history before start" } } } };
    const listeners = new Set();
    const store = { getState: () => state, dispatch() {}, subscribe(fn) { listeners.add(fn); return () => listeners.delete(fn); } };
    const publish = messages => { state.newLiveTranscription = { newLTMessage: messages }; for (const fn of [...listeners]) fn(); };
    const now = () => state.newLiveTranscription.newLTMessage;
    const frame = document.createElement("iframe"); frame.id = "webclient"; document.body.append(frame);
    const doc = frame.contentDocument, root = doc.createElement("div"), inner = doc.createElement("div"); root.append(inner); doc.body.append(root);
    eq(call("discover").code, "ZOOM_STORE_NOT_FOUND", "no store yet");
    root["__reactContainer$test"] = { memoizedProps: {}, child: { memoizedProps: {}, sibling: { memoizedProps: { store } } } };
    const ready = call("discover"); eq([ready.code, ready.captionReady, ready.platform], ["READY", true, "Zoom"], "store found through the React container");
    eq(listeners.size, 0, "nothing subscribed before consent");
    eq(call("start").status, "live", "starts");
    eq(listeners.size, 1, "one read-only subscription");
    publish({ ...now(), old: { ...now().old, text: "history before start and growth" } });
    eq(texts(), [], "history and its growth stay private");
    publish({ ...now(), n1: { msgId: "n1", user: { zoomID: 2, displayName: "Bob Example" }, text: "hello" } });
    publish({ ...now(), n1: { msgId: "n1", user: { zoomID: 2, displayName: "Bob Example" }, text: "hello world" } });
    eq(texts(), [["speaker-2", "Bob Example", "hello world"]], "new message is upserted under one id with its display name");
    eq(JSON.stringify(call("read")).includes("zoomID"), false, "internal ids never leave the page");
    const before = doc.documentElement.outerHTML; call("read"); eq(doc.documentElement.outerHTML, before, "reader never mutates the page");
    call("reset"); eq(listeners.size, 0, "unsubscribed on reset");
    owner = "zoom-2"; call("start"); await new Promise(r => setTimeout(r, 2150));
    eq(call("read").code, "CAPTURE_EXPIRED", "lease expires"); eq(listeners.size, 0, "unsubscribed on expiry");
    eq(call("recover", { captureId: "zoom-3", previousCaptureId: owner }).status, "live", "recover continues"); owner = "zoom-3";
    publish({ ...now(), n2: { msgId: "n2", user: { zoomID: 3, displayName: "Carol Example" }, text: "after recovery" } });
    eq(texts().map(x => x[2]), ["after recovery"], "what was on screen at recovery is excluded again");
    call("reset");
    return { ok: true, checks };
  };
  const result = await runInChrome(t, { hook: "zoom-hook.js", hostname: "app.zoom.us", pathname: "/wc/12345678/join", suite });
  assert.ok(result.checks >= 12);
  t.diagnostic(`Chrome DOM (Zoom store): ${result.checks} assertions on a synthetic store; no live meeting.`);
});
