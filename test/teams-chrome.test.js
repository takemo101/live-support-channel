import test from "node:test";
import assert from "node:assert/strict";
import { chrome, runInChrome } from "../test-support/chrome.js";

test("real Chrome: Teams captions are intercepted from the call's remote-event handler (WeakRef context, original always called)", { skip: !chrome, timeout: 40000 }, async t => {
  const suite = async function (window, capture) {
    let checks = 0, owner = "teams-1";
    const eq = (a, b, name) => { if (JSON.stringify(a) !== JSON.stringify(b)) throw Error(name + ": " + JSON.stringify(a)); checks++; };
    const call = (action, extra = {}) => capture({ action, meetingId: "teams.microsoft.com/call", captureId: owner, ...extra });
    const item = (ts, user, version, text) => ({ id: "m" + ts + "/" + version, userId: user, timestampAudioSent: ts, text });
    const seen = [];
    const on = { name: "remoteUserEventsReceived", handler(type, payload) { seen.push([type, typeof payload]); } };
    const activeCall = { participants: [{ mri: "u1", displayName: "Alice Example" }], dataChannel: { subscriptions: [{ eventHandler: { on } }] } };
    let live = null;
    const context = { callingService: { getActiveCall: () => live } };
    window.msteamscalling = new WeakRef(context);
    const send = (...items) => on.handler("3", JSON.stringify({ recognitionResults: items }));
    const texts = () => call("read").blocks.map(b => [b.deviceId, b.speakerName, b.transcript, b.messageVersion]);
    eq(call("discover").code, "TEAMS_CALL_NOT_FOUND", "no active call yet");
    live = activeCall; const original = on.handler;
    const meta = call("discover"); eq([meta.code, meta.captionReady, meta.platform], ["READY", true, "Teams"], "the call's handler is found through the WeakRef context");
    eq(on.handler === original, true, "nothing patched before consent");
    eq(call("start").status, "live", "starts"); eq(on.handler === original, false, "handler wrapped after start");
    send(item(100, "u1", 1, "private baseline")); send(item(100, "u1", 2, "private baseline revised"));
    eq(texts(), [], "history is never sent");
    send(item(101, "u1", 1, "fresh caption")); send(item(101, "u1", 2, "fresh caption revised"));
    eq(texts(), [["speaker-1", "Alice Example", "fresh caption revised", 2]], "revisions are upserted under one id with the participant's name");
    eq(JSON.stringify(call("read")).includes("u1"), false, "the internal user id never leaves the page");
    on.handler("3", "not json"); on.handler("7", "x"); eq(seen.length, 6, "every event, including non-captions, still reaches the app's handler");
    call("reset"); eq(on.handler === original, true, "original handler restored");
    owner = "teams-2"; call("start"); await new Promise(r => setTimeout(r, 2150));
    eq(call("read").code, "CAPTURE_EXPIRED", "lease expires"); eq(on.handler === original, true, "handler restored on expiry");
    eq(call("recover", { captureId: "teams-3", previousCaptureId: owner }).status, "live", "recover continues"); owner = "teams-3";
    send(item(300, "u1", 1, "first after recovery")); send(item(301, "u1", 1, "second after recovery"));
    eq(texts().map(x => x[2]), ["second after recovery"], "first utterance is history again after recovery");
    live = null; eq(call("read").code, "TEAMS_CALL_ENDED", "the call ending stops the capture"); eq(on.handler === original, true, "handler restored when the call ends");
    call("reset");
    return { ok: true, checks };
  };
  const result = await runInChrome(t, { hook: "teams-hook.js", hostname: "teams.microsoft.com", pathname: "/v2/", suite });
  assert.ok(result.checks >= 14);
  t.diagnostic(`Chrome (Teams call handler): ${result.checks} assertions on a synthetic call; no live meeting.`);
});
