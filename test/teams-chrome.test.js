import test from "node:test";
import assert from "node:assert/strict";
import { chrome, runInChrome } from "../test-support/chrome.js";

test("real Chrome DOM: Teams captions are read from the visible live-caption list only", { skip: !chrome, timeout: 40000 }, async t => {
  const suite = async function (window, capture) {
    let checks = 0, owner = "teams-1";
    const eq = (a, b, name) => { if (JSON.stringify(a) !== JSON.stringify(b)) throw Error(name + ": " + JSON.stringify(a)); checks++; };
    const tick = () => new Promise(r => setTimeout(r, 30));
    const call = (action, extra = {}) => capture({ action, meetingId: "teams.microsoft.com/call", captureId: owner, ...extra });
    const mount = () => { const list = document.createElement("div"); list.setAttribute("data-tid", "closed-caption-v2-virtual-list-content"); document.body.append(list); return list; };
    // Synthetic layout: <item><div>label</div><div><span>text</span></div></item>. Names and text are fake.
    const addRow = (list, name, text) => {
      const item = document.createElement("div"), label = document.createElement("div"), body = document.createElement("div"), span = document.createElement("span");
      label.textContent = name; span.textContent = text; body.append(span); item.append(label, body); list.append(item); return span;
    };
    const texts = () => call("read").blocks.map(b => b.transcript);
    document.body.innerHTML = "<p id='roster'>Alice</p>";
    const unavailable = call("discover"); eq([unavailable.code, unavailable.captionReady], ["TEAMS_CAPTIONS_NOT_FOUND", false], "no caption list: not ready");
    eq(call("start").code, "TEAMS_CAPTIONS_NOT_FOUND", "start refuses without captions on screen");
    let list = mount(); const old = addRow(list, "Alice Example", "history before start");
    eq(call("discover").code, "READY", "caption list found"); eq(call("discover").diagnostics.received, 0, "nothing processed before consent");
    eq(call("start").status, "live", "starts");
    old.textContent = "history before start and more"; await tick();
    eq(texts(), [], "text that was already showing at start is never sent, including its growth");
    const fresh = addRow(list, "Bob Example", "hello"); await tick();
    fresh.textContent = "hello world"; await tick();
    eq(texts(), ["hello world"], "new row is upserted under one id");
    eq(call("read").blocks[0].messageVersion >= 2, true, "revisions counted");
    fresh.textContent = "hello, world!"; await tick();
    eq(texts(), ["hello, world!"], "in-place correction replaces the same utterance");
    addRow(list, "Alice Example", "other speaker"); await tick();
    eq(call("read").blocks.map(b => [b.deviceId, b.speakerName]), [["speaker-2", "Bob Example"], ["speaker-1", "Alice Example"]], "the visible display name is sent; the same label is the same speaker, numbered by first sight");
        fresh.textContent = "a completely new sentence"; await tick();
    eq(texts(), ["hello, world!", "other speaker", "a completely new sentence"], "unrelated text on a reused row is a new utterance");
    const before = document.documentElement.outerHTML; call("read"); eq(document.documentElement.outerHTML, before, "reader never mutates the page");
    const rerender = list.lastElementChild; const copy = rerender.cloneNode(true); rerender.replaceWith(copy); await tick(); call("read");
    eq(texts().filter(x => x === "other speaker").length, 1, "a re-rendered row of an already seen utterance is not sent again");
    list.firstElementChild.remove(); eq(call("read").status, "live", "virtualised rows disappearing is not an error");
    list.remove(); await tick(); eq(call("read").status, "live", "caption list disappearing is not an error");
    list = mount(); const again = addRow(list, "Bob Example", "after remount"); await tick(); call("read"); again.textContent = "after remount grows"; await tick();
    eq(texts().includes("after remount grows"), true, "a new caption list is re-observed");
    addRow(list, "Eve\u202Edanger\u0000 " + "x".repeat(100), "hostile label"); await tick();
    const hostile = call("read").blocks.find(b => b.transcript === "hostile label");
    eq([hostile.speakerName.length <= 64, /[\p{Cc}\u202e]/u.test(hostile.speakerName), hostile.speakerName.startsWith("Eve danger")], [true, false, true], "a hostile label is sanitised and bounded");
    list.append(Object.assign(document.createElement("div"), { textContent: "unstructured text" })); list.innerHTML = "<div>no label rows</div>";
    eq(call("read").code, "CAPTION_FORMAT_UNKNOWN", "unknown structure stops instead of guessing");
    eq(call("read").diagnostics.unmatched >= 1, true, "unmatched count reported");
    eq(call("read").diagnostics.tids, [], "no data-tid names without a wrapper"); call("reset");
    list.innerHTML = ""; const keep = addRow(list, "Bob Example", "existing again");
    owner = "teams-2"; call("start"); await new Promise(r => setTimeout(r, 2150));
    eq(call("read").code, "CAPTURE_EXPIRED", "lease expires");
    eq(call("recover", { captureId: "teams-3", previousCaptureId: owner }).status, "live", "recover continues");
    owner = "teams-3"; keep.textContent = "existing again, grown"; await tick();
    eq(texts(), [], "text showing at recovery is excluded again");
    addRow(list, "Bob Example", "brand new"); await tick();
    eq(texts(), ["brand new"], "new rows after recovery are read");
    call("reset");
    return { ok: true, checks };
  };
  const result = await runInChrome(t, { hook: "teams-hook.js", hostname: "teams.microsoft.com", pathname: "/v2/", suite });
  assert.ok(result.checks >= 20);
  t.diagnostic(`Chrome DOM (Teams): ${result.checks} assertions on a synthetic caption list; no live meeting.`);
});
